// Store for repositories data
let allRepositories = [];

// Shared observer for scroll animations
let scrollObserver = null;

// Escape HTML coming from external data (repos.json / GitHub API)
function escapeHtml(value) {
    return String(value == null ? '' : value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;');
}

// Fetch repositories: local snapshot first, live GitHub API as fallback
async function fetchRepositories() {
    const reposList = document.getElementById('repos-list');

    let repos = null;
    let source = null;

    // 1) Local snapshot generated by the update-repos workflow (no rate limits)
    try {
        const response = await fetch('repos.json');
        if (response.ok) {
            repos = await response.json();
            source = 'repos.json';
        }
    } catch (error) {
        console.warn('Could not load repos.json:', error);
    }

    // 2) Live GitHub API fallback (unauthenticated, may hit rate limits)
    if (!Array.isArray(repos) || repos.length === 0) {
        try {
            const response = await fetch('https://api.github.com/users/0ldskoolerz/repos?sort=updated&per_page=50');
            if (response.ok) {
                repos = await response.json();
                source = 'github api';
            }
        } catch (error) {
            console.warn('Could not reach the GitHub API:', error);
        }
    }

    if (!Array.isArray(repos)) {
        reposList.innerHTML = '<p class="loading">Unable to load repositories right now. You can also browse them on <a href="https://github.com/0ldskoolerz" target="_blank" style="color:inherit">my GitHub profile</a>.</p>';
        return;
    }

    if (repos.length === 0) {
        reposList.innerHTML = '<p class="loading">No repositories found yet.</p>';
        return;
    }

    // Store repositories and categorize them
    allRepositories = repos.map(repo => ({
        ...repo,
        category: categorizeRepository(repo)
    }));

    // Update repo count
    document.getElementById('repo-count').textContent = repos.length;

    // Render all repositories initially
    renderRepositories(allRepositories);
    animateCards();

    console.log('Repositories loaded from ' + source + ':', allRepositories.length);
}

// Categorize repository based on language or name
function categorizeRepository(repo) {
    const name = repo.name.toLowerCase();
    const language = repo.language || '';

    // Web category
    if (language === 'HTML' || language === 'CSS' ||
        name.includes('web') || name.includes('site') || name.includes('github.io')) {
        return 'web';
    }

    // JavaScript category
    if (language === 'JavaScript' || language === 'TypeScript' ||
        name.includes('app') || name.includes('js')) {
        return 'javascript';
    }

    // Projects category (more substantial projects)
    if (repo.topics && repo.topics.length > 0) {
        return 'projects';
    }

    return 'other';
}

// Render repositories
function renderRepositories(repos) {
    const reposList = document.getElementById('repos-list');

    if (repos.length === 0) {
        reposList.innerHTML = '<p class="loading">No repositories match the selected category.</p>';
        return;
    }

    reposList.innerHTML = repos.map(repo => `
        <div class="repo-card" data-category="${escapeHtml(repo.category)}">
            <h3>
                <a href="${escapeHtml(repo.html_url)}" target="_blank" class="repo-link">
                    ${escapeHtml(repo.name)}
                </a>
            </h3>
            <p class="description">${escapeHtml(repo.description || 'No description available')}</p>
            <div class="repo-meta">
                ${repo.language ? `<span>&#128221; ${escapeHtml(repo.language)}</span>` : ''}
                <span>&#11088; ${escapeHtml(repo.stargazers_count)}</span>
                ${repo.forks_count > 0 ? `<span>&#128256; ${escapeHtml(repo.forks_count)}</span>` : ''}
            </div>
            <a href="${escapeHtml(repo.html_url)}" target="_blank" class="btn btn-primary">View Repository</a>
        </div>
    `).join('');
}

// Setup category filters
function setupCategoryFilters() {
    const categoryTabs = document.querySelectorAll('.category-tab');

    categoryTabs.forEach(tab => {
        tab.addEventListener('click', function() {
            const category = this.getAttribute('data-category');

            // Update active tab
            categoryTabs.forEach(t => t.classList.remove('active'));
            this.classList.add('active');

            // Filter and render repositories
            if (category === 'all') {
                renderRepositories(allRepositories);
            } else {
                const filtered = allRepositories.filter(repo => repo.category === category);
                renderRepositories(filtered);
            }
        });
    });
}

// Smooth scroll behavior for navigation links
function setupSmoothScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            const href = this.getAttribute('href');
            if (href !== '#' && document.querySelector(href)) {
                e.preventDefault();
                const element = document.querySelector(href);
                element.scrollIntoView({ behavior: 'smooth', block: 'start' });
            }
        });
    });
}

// Scroll animation for cards (works for content cards and repo cards,
// including the ones rendered after the repositories load)
function getScrollObserver() {
    if (scrollObserver) return scrollObserver;
    scrollObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.style.opacity = '1';
                entry.target.style.transform = 'translateY(0)';
                scrollObserver.unobserve(entry.target);
            }
        });
    }, {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    });
    return scrollObserver;
}

function animateCards() {
    document.querySelectorAll('.repo-card, .content-card').forEach(el => {
        if (el.dataset.animated) return;
        el.dataset.animated = '1';
        el.style.opacity = '0';
        el.style.transform = 'translateY(20px)';
        el.style.transition = 'all 0.6s ease';
        getScrollObserver().observe(el);
    });
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', function() {
    // Current year in the footer
    const yearEl = document.getElementById('year');
    if (yearEl) yearEl.textContent = new Date().getFullYear();

    fetchRepositories();
    setupCategoryFilters();
    setupSmoothScroll();
    animateCards();
});
